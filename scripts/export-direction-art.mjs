// Copy selected original PNG bytes and emit calibrated static model data. No pixel editing.
import {readFile,writeFile,copyFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {readRgbaPng} from './lib/rgba-png.mjs';
const source='docs/design/art-workflow/d1-directions-v1',out='web/upstream/whale/directions',check=process.argv.includes('--check');
const hash=b=>createHash('sha256').update(b).digest('hex');
const model=JSON.parse(await readFile(source+'/model.json'));model.status='product-main-colour';
const exports=new Map();
for(const def of Object.values(model.directions)){const name=def.atlas.split('/').at(-1);def.atlas=name;exports.set(name,await readFile(source+'/source/'+name));}
const head='back-head-no-bow-v1.png',bytes=await readFile(source+'/source/'+head);exports.set(head,bytes);
const {pixels,width,height}=readRgbaPng(bytes),def=model.directions.backRight;def.headAtlas=head;
const regions=JSON.parse(await readFile(source+'/source/atlas-regions.json'));
const [x,y,w,h]=regions.backRight.parts.head.region;let a=width,b=height,c=0,d=0;
for(let j=y;j<y+h;j++)for(let i=x;i<x+w;i++)if(pixels[(j*width+i)*4+3]>=16){a=Math.min(a,i);b=Math.min(b,j);c=Math.max(c,i);d=Math.max(d,j);}
def.parts.find(p=>p.id==='head').uvBox=[(a-2)/width,(b-2)/height,(c+3)/width,(d+3)/height];
const json=JSON.stringify(model,null,2);exports.set('model.json',Buffer.from(json+'\n'));exports.set('model.js',Buffer.from('// Generated by scripts/export-direction-art.mjs; do not edit.\nexport default '+json+';\n'));
const provenance=JSON.parse(await readFile(source+'/source/product-export.json'));provenance.files=Object.fromEntries([...exports].map(([n,b])=>[n,hash(b)]));
exports.set('provenance.json',Buffer.from(JSON.stringify(provenance,null,2)+'\n'));
if(!check)await mkdir(out,{recursive:true});
for(const [name,content]of exports){if(check){if(!(await readFile(out+'/'+name)).equals(content))throw Error('Stale export: '+name);}else await writeFile(out+'/'+name,content);}
console.log(`Direction export ${check?'verified':'written'}: ${exports.size} files; original PNG bytes retained.`);
