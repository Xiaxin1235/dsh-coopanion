import assert from 'node:assert/strict';
import { once } from 'node:events';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from '../scripts/lib/playwright.mjs';
import { previewServer } from '../scripts/preview.mjs';
const directory = await mkdtemp(join(tmpdir(), 'dsh-mouth-'));
const server = previewServer({ dataDir: directory }); server.listen(0, '127.0.0.1'); await once(server, 'listening');
let browser;
try {
  browser = await chromium.launch({ headless:true, args:['--no-sandbox','--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport:{width:1000,height:750} });
  await page.route('**/upstream/kit/body.js', async route => { const response = await route.fetch(), source = await response.text(); assert.ok(source.includes('custom.draw(petG, face, {')); await route.fulfill({response, body:source.replace('custom.draw(petG, face, {', 'window.mouthOpenness = pet.talkK; custom.draw(petG, face, {')}); });
  await page.goto(`http://127.0.0.1:${server.address().port}`); await page.waitForSelector('#pet[data-mode]');
  const body = page.frames().find(frame => frame.url().includes('figure-frame.html'));
  await body.evaluate(() => { window.mouthPulses = []; addEventListener('message', event => { if(event.data?.t === 'talk') window.mouthPulses.push(performance.now()); }); });
  await page.locator('[data-demo=talking]').click();
  await body.waitForFunction(() => window.mouthPulses.length > 0);
  await page.waitForTimeout(2200);
  const before = await body.evaluate(() => window.mouthPulses.length);
  await page.waitForTimeout(600);
  const after = await body.evaluate(() => window.mouthPulses.length);
  console.log(JSON.stringify({before,after,mood:await page.locator('#pet').getAttribute('data-mood')}));
  assert.ok(await body.evaluate(() => window.mouthOpenness < .02), 'the actual rendered mouth envelope settles closed');
  assert.equal(after, before, 'unchanged talking status must not reopen the mouth indefinitely without fresh output');
  await page.locator('[data-demo=talking]').click();
  await body.waitForFunction(count => window.mouthPulses.length > count, after);
  console.log('Fresh output renews mouth movement; unchanged state settles.');
  await page.addInitScript(() => { window.dshPetBridge = { subscribe(fn) { window.receiveMouth = fn; }, action() {}, hit() {} }; });
  await page.reload(); await page.waitForSelector('#pet[data-mode]');
  const liveBody = page.frames().find(frame => frame.url().includes('figure-frame.html'));
  await liveBody.evaluate(() => { window.mouthPulses = []; addEventListener('message', event => { if(event.data?.t === 'talk') window.mouthPulses.push(performance.now()); }); });
  const live = progress => ({type:'snapshot', snapshot:{sessionId:'live', mood:'talking', active:true, streaming:true, speechRevision:progress, revision:1, sessions:[{id:'live',mood:'talking',active:true,streaming:true,speechRevision:progress,revision:1}],results:[]}});
  await page.evaluate(value => window.receiveMouth(value), live(1));
  await liveBody.waitForFunction(() => window.mouthPulses.length > 0);
  await page.waitForTimeout(1600);
  const quiet = await liveBody.evaluate(() => window.mouthPulses.length);
  await page.evaluate(value => window.receiveMouth(value), live(1));
  await page.waitForTimeout(400);
  assert.equal(await liveBody.evaluate(() => window.mouthPulses.length), quiet, 'identical snapshots cannot revive the mouth');
  await page.evaluate(value => window.receiveMouth(value), live(2));
  await liveBody.waitForFunction(count => window.mouthPulses.length > count, quiet);
  console.log('Real metadata progress renews mouth movement; repeated snapshots stay quiet.');
} finally { await browser?.close(); await new Promise(resolve => server.close(resolve)); await rm(directory,{recursive:true,force:true}); }
