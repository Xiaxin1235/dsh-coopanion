import assert from 'node:assert/strict';
import { once } from 'node:events';
import { mkdir, mkdtemp, rm } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium, artifactRoot } from '../scripts/lib/playwright.mjs';
import { previewServer } from '../scripts/preview.mjs';

const directory = await mkdtemp(join(tmpdir(), 'dsh-inbox-ui-'));
const server = previewServer({ dataDir: directory }); server.listen(0, '127.0.0.1'); await once(server, 'listening');
let browser;
try {
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH ?? (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : chromium.executablePath()), headless: true, args: ['--no-sandbox', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 1200, height: 800 }, reducedMotion: 'reduce' });
  page.setDefaultTimeout(12000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
    window.inboxActions = [];
    window.dshPetBridge = { subscribe(fn) { window.inboxReceive = fn; }, action(value) { window.inboxActions.push(value); }, hit() {} };
  });
  const receive = message => page.evaluate(message => window.inboxReceive(message), message);
  const actions = () => page.evaluate(() => window.inboxActions.filter(action => ['select', 'read', 'open-session', 'notification-snooze'].includes(action.type)));
  const resetActions = () => page.evaluate(() => { window.inboxActions = []; });
  const focus = { id: 'focus-full-id', label: '正在聊的会话', project: 'shared', mood: 'idle', unread: 0, chatAvailable: true };
  const a = { id: 'source-abcdef-111', label: '修复状态', project: 'shared', mood: 'idle', unread: 1, chatAvailable: true };
  const b = { ...a, id: 'source-abcdef-222', label: '检查菜单' };
  const reply = (id, session, time, text) => ({ id, sessionId: session.id, time, text, read: false });
  const first = reply('single-full-reply', a, 1, '完整回复。\n' + '最终结果🐳。'.repeat(80));
  const frame = (sessions, results) => ({ mood: 'idle', active: false, sessionId: focus.id, sessions: [focus, ...sessions], results });
  const state = { protocol: 1, runtime: { phase: 'running', visible: true, generation: 8, visibilityRevision: 4, suspended: false }, interactions: [] };
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.waitForSelector('#pet[data-character=whale][data-mode]');
  await receive({ type: 'init', options: { locale: 'zh-CN', roam: false }, snapshot: frame([a], [first]) });
  await receive({ type: 'notification-state', snapshot: state });
  await resetActions();
  await page.locator('#attention').click();
  await page.locator('#reader:not([hidden])').waitFor();
  assert.equal(await page.locator('#reader-text').innerText(), first.text, 'one reply opens in full with one click');
  assert.equal(await page.locator('#conversations').isVisible(), false);
  assert.equal(await page.locator('#chat-session-name').innerText(), focus.label);
  assert.deepEqual(await actions(), [{ type: 'read', resultId: first.id }], 'reading acknowledges the exact reply and keeps chat focus');
  await page.keyboard.press('Escape');

  const second = reply('multi-a-full', a, 2, '<img src=x onerror="throw 1"> 已修复状态。\n全文内容。');
  const third = reply('multi-b-full', b, 3, '菜单已经完成。');
  const request = { id: JSON.stringify([a.id, 'question', 'question-call-full']), nativeId: 'question-call-full', sessionId: a.id, kind: 'question', turn: 1, seq: 2, createdAt: 1, preview: '这一步选择哪个方案？', state: 'continued', dueAt: null, automaticReminders: 0 };
  const issue = { id: 'error-source-full', label: '构建检查', mood: 'error', text: '构建失败，请检查。', unread: 0 };
  const waitingA = { ...a, mood: 'waiting' };
  await receive({ type: 'snapshot', snapshot: frame([waitingA, b, issue], [{ ...first, read: true }, second, third]) });
  await receive({ type: 'notification-state', snapshot: { ...state, interactions: [request] } });
  await resetActions();
  await page.locator('#attention').click();
  await page.locator('#requests:not([hidden])').waitFor();
  assert.equal(await page.locator('#inbox-replies .inbox-reply').count(), 2);
  assert.equal(await page.locator('.request-card').count(), 1);
  assert.equal(await page.locator('#inbox-issues .inbox-issue').count(), 1);
  assert.equal(await page.locator('#attention-count').innerText(), '4', 'a question is not counted again as a generic waiting session');
  assert.equal(await page.locator('#inbox-replies img').count(), 0, 'reply summaries are plain text');
  assert.deepEqual(await actions(), [], 'opening a list neither reads replies nor selects a conversation');
  await page.locator(`[data-result-id="${second.id}"][data-action=open]`).click();
  assert.deepEqual(await actions(), [{ type: 'read', resultId: second.id }, { type: 'select', sessionId: a.id }], 'a reply row continues its exact source in the composer');

  await page.locator('#chat-close').click();
  const fourth = reply('multi-c-full', a, 4, '另一份完整回复。');
  await receive({ type: 'snapshot', snapshot: frame([waitingA, b, issue], [{ ...second, read: true }, third, fourth]) });
  await resetActions();
  await page.locator('#attention').click();
  await page.locator(`[data-result-id="${fourth.id}"][data-action=read]`).focus();
  assert.deepEqual(await actions(), [], 'keyboard focus on a summary does not mark it read');
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#reader-text').innerText(), fourth.text);
  assert.equal(await page.locator('#reader-count').innerText(), '1 / 2');
  const incoming = reply('arrives-while-reading', b, 5, '读到一半新收到的回复。');
  await receive({ type: 'snapshot', snapshot: frame([waitingA, b, issue], [third, fourth, incoming]) });
  assert.equal(await page.locator('#reader-text').innerText(), fourth.text, 'incoming messages cannot replace the open reply');
  assert.equal(await page.locator('#reader-count').innerText(), '1 / 2', 'the active reading order remains stable');
  await page.locator('#reader-next').click();
  assert.equal(await page.locator('#reader-text').innerText(), third.text, 'read consecutively across source sessions');
  assert.equal(await page.locator('#chat-session-name').innerText(), focus.label);
  assert.ok(!(await actions()).some(action => action.type === 'select'));
  await page.locator('#reader-inbox').click();
  assert.equal(await page.locator('#inbox-replies .inbox-reply').count(), 1, 'returning reveals the new unread reply');
  await resetActions();
  await page.locator('[data-request-id][data-action=open]').click();
  assert.deepEqual(await actions(), [{ type: 'open-session', sessionId: a.id }], 'opening a question never reads replies or settles the request');
  await page.locator('#attention').click();
  assert.equal(await page.locator('.request-card').count(), 1);
  await page.locator('[data-request-id][data-action=snooze]').focus();
  await receive({ type: 'notification-state', snapshot: { ...state, interactions: [{ ...request, dueAt: Date.now() + 600000 }] } });
  assert.equal(await page.evaluate(() => document.activeElement.dataset.requestId), request.id, 'request updates preserve keyboard focus on the same action');
  await page.locator('[data-request-id][data-action=snooze]').click();
  assert.deepEqual((await actions()).at(-1), { type: 'notification-snooze', interactionId: request.id, generation: 8 });
  await receive({ type: 'notification-snooze-result', interactionId: request.id, ok: true });
  await receive({ type: 'configure', options: { locale: 'en-US' } });
  assert.equal(await page.locator('#requests-title').innerText(), 'Brought back for you');
  assert.equal(await page.locator('#inbox-replies [data-action=open]').innerText(), 'Continue conversation ↗');
  await page.setViewportSize({ width: 320, height: 640 });
  await page.waitForFunction(() => { const r = document.getElementById('requests').getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && r.top >= 0 && r.bottom <= innerHeight; });
  assert.equal(await page.locator('#requests').evaluate(el => el.scrollWidth <= el.clientWidth), true, 'the inbox fits a small viewport');
  await page.locator('#inbox-list').evaluate(el => { el.scrollTop = 0; });
  await mkdir(artifactRoot, { recursive: true }); await page.screenshot({ path: `${artifactRoot}/inbox-narrow.png` });
  await page.setViewportSize({ width: 1200, height: 800 });
  await receive({ type: 'configure', options: { locale: 'zh-CN' } });
  await page.waitForFunction(() => {
    const panel = document.getElementById('requests'), pet = document.getElementById('pet').getBoundingClientRect();
    const tail = panel.getBoundingClientRect().left + parseFloat(panel.style.getPropertyValue('--tail'));
    return Math.abs(tail - (pet.left + pet.width / 2)) < 80;
  });
  await page.locator('#inbox-list').evaluate(el => { el.scrollTop = 0; });
  await receive({ type: 'snapshot', snapshot: frame([waitingA, b, { ...issue, mood: 'idle' }], [third, fourth, incoming]) });
  assert.equal(await page.locator('#inbox-issues .inbox-issue').count(), 0, 'a recovered error leaves the inbox');
  const clip = await page.evaluate(() => {
    const panel = document.getElementById('requests').getBoundingClientRect(), pet = document.getElementById('pet').getBoundingClientRect();
    const x = Math.max(0, Math.floor(Math.min(panel.left, pet.left) - 18)), y = Math.max(0, Math.floor(Math.min(panel.top, pet.top) - 18));
    return { x, y, width: Math.min(innerWidth - x, Math.ceil(Math.max(panel.right, pet.right) - x + 18)), height: Math.min(innerHeight - y, Math.ceil(Math.max(panel.bottom, pet.bottom) - y + 18)) };
  });
  await page.screenshot({ path: `${artifactRoot}/session-inbox.png`, clip });
  assert.deepEqual(errors, []);
  console.log('Inbox UI passed: one-click full reply, direct source actions, mixed pending items, stable chat focus and reading order, Unicode/text safety, bilingual copy and narrow layout.');
} finally { await browser?.close(); await new Promise(resolve => server.close(resolve)); await rm(directory, { recursive: true, force: true }); }
